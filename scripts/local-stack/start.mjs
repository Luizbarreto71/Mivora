#!/usr/bin/env node
/**
 * Local Supabase-compatible stack for development and E2E tests — NOT for production.
 *
 *   Postgres (port 54322)  ← migrations from supabase/migrations
 *   PostgREST (port 54323) ← the same REST engine Supabase uses
 *   Gateway (port 54321)   ← /rest/v1 proxy + minimal /auth/v1 and /storage/v1 emulation
 *
 * Requirements: PostgreSQL binaries (initdb, pg_ctl, psql) and the PostgREST binary.
 *   PG_BIN=/path/to/pgsql/bin POSTGREST_BIN=/path/to/postgrest node scripts/local-stack/start.mjs [--reset]
 *
 * Writes .env.local (only when absent or previously generated by this script).
 */
import { spawn, spawnSync } from "node:child_process";
import { createHmac, randomUUID, timingSafeEqual } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync, createReadStream, unlinkSync } from "node:fs";
import http from "node:http";
import path from "node:path";

const root = process.cwd();
const stateDir = path.join(root, ".local-stack");
const cfg = {
  pgBin: process.env.PG_BIN ?? "C:/Users/User/tools/pgsql/bin",
  postgrest: process.env.POSTGREST_BIN ?? "C:/Users/User/tools/postgrest/postgrest.exe",
  pgPort: Number(process.env.PG_PORT ?? 54322),
  restPort: Number(process.env.PGRST_PORT ?? 54323),
  gatewayPort: Number(process.env.GATEWAY_PORT ?? 54321),
  db: "mivora_local",
  jwtSecret: process.env.LOCAL_JWT_SECRET ?? "local-development-secret-at-least-32-characters",
  adminEmail: process.env.LOCAL_ADMIN_EMAIL ?? "admin@mivora.local",
  adminPassword: process.env.LOCAL_ADMIN_PASSWORD ?? "mivora-local-123",
};
const dataDir = path.join(stateDir, "pgdata");
const storageDir = path.join(stateDir, "storage");
const bin = (name) => path.join(cfg.pgBin, process.platform === "win32" ? `${name}.exe` : name);

function run(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, { encoding: "utf8", ...opts });
  if (r.status !== 0 && !opts.allowFail) {
    console.error(r.stdout, r.stderr);
    throw new Error(`${path.basename(cmd)} ${args.join(" ")} failed`);
  }
  return r;
}
const psql = (args, opts) => run(bin("psql"), ["-h", "localhost", "-p", String(cfg.pgPort), "-U", "postgres", "-v", "ON_ERROR_STOP=1", ...args], opts);

// ---------------------------------------------------------------------------
// JWT (HS256) helpers
// ---------------------------------------------------------------------------
const b64url = (buf) => Buffer.from(buf).toString("base64url");
function signJwt(payload) {
  const head = b64url(JSON.stringify({ alg: "HS256", typ: "JWT" }));
  const body = b64url(JSON.stringify(payload));
  const sig = createHmac("sha256", cfg.jwtSecret).update(`${head}.${body}`).digest("base64url");
  return `${head}.${body}.${sig}`;
}
function verifyJwt(token) {
  const [head, body, sig] = (token ?? "").split(".");
  if (!sig) return null;
  const expected = createHmac("sha256", cfg.jwtSecret).update(`${head}.${body}`).digest();
  const given = Buffer.from(sig, "base64url");
  if (given.length !== expected.length || !timingSafeEqual(given, expected)) return null;
  const payload = JSON.parse(Buffer.from(body, "base64url").toString());
  if (payload.exp && payload.exp < Date.now() / 1000) return null;
  return payload;
}
const anonKey = signJwt({ role: "anon", iss: "mivora-local", iat: 1700000000, exp: 4102444800 });

// ---------------------------------------------------------------------------
// Postgres
// ---------------------------------------------------------------------------
if (process.argv.includes("--reset")) rmSync(stateDir, { recursive: true, force: true });
mkdirSync(storageDir, { recursive: true });
if (!existsSync(path.join(dataDir, "PG_VERSION"))) {
  console.log("• initdb");
  run(bin("initdb"), ["-D", dataDir, "-U", "postgres", "--auth=trust", "-E", "UTF8", "--locale=C"]);
}
// stdio must not be piped: the postmaster inherits it and spawnSync would never return
if (spawnSync(bin("pg_ctl"), ["-D", dataDir, "status"], { stdio: "ignore" }).status !== 0)
  spawnSync(bin("pg_ctl"), ["-D", dataDir, "-o", `-p ${cfg.pgPort}`, "-l", path.join(stateDir, "postgres.log"), "-w", "start"], { stdio: "ignore" });

const exists = psql(["-tAc", `select 1 from pg_database where datname = '${cfg.db}'`]).stdout.trim() === "1";
if (!exists) {
  console.log("• creating database and applying migrations");
  psql(["-c", `create database ${cfg.db}`]);
  psql(["-d", cfg.db, "-f", path.join(root, "scripts/local-stack/supabase-stub.sql")]);
  const migrations = readdirSync(path.join(root, "supabase/migrations")).filter((f) => f.endsWith(".sql")).sort();
  for (const m of migrations) {
    console.log(`  - ${m}`);
    psql(["-d", cfg.db, "-q", "-f", path.join(root, "supabase/migrations", m)]);
  }
  psql(["-d", cfg.db, "-c", `insert into auth.users (email) values ('${cfg.adminEmail}'); select public.grant_admin_by_email('${cfg.adminEmail}', 'owner');`]);
}
const adminId = psql(["-d", cfg.db, "-tAc", `select id from auth.users where email = '${cfg.adminEmail}'`]).stdout.trim();

// ---------------------------------------------------------------------------
// PostgREST
// ---------------------------------------------------------------------------
let shuttingDown = false;
let restarts = 0;
function startRest() {
  const proc = spawn(cfg.postgrest, [], {
    env: {
      ...process.env,
      PGRST_DB_URI: `postgres://authenticator@localhost:${cfg.pgPort}/${cfg.db}`,
      PGRST_DB_SCHEMAS: "public",
      PGRST_DB_ANON_ROLE: "anon",
      PGRST_JWT_SECRET: cfg.jwtSecret,
      PGRST_SERVER_PORT: String(cfg.restPort),
      PGRST_DB_POOL: "10",
      PGRST_LOG_LEVEL: "warn",
    },
    stdio: ["ignore", "inherit", "inherit"],
  });
  // PostgREST occasionally exits right after a fresh database is created: restart it
  proc.on("exit", (code) => {
    if (shuttingDown) return;
    console.log(`PostgREST exited (code ${code}); restarting…`);
    if (++restarts <= 10) setTimeout(() => (rest = startRest()), 1500);
  });
  return proc;
}
let rest = startRest();

// ---------------------------------------------------------------------------
// Gateway
// ---------------------------------------------------------------------------
const MIME = { webp: "image/webp", jpg: "image/jpeg", jpeg: "image/jpeg", png: "image/png", avif: "image/avif" };
const json = (res, status, body) => {
  res.writeHead(status, { "content-type": "application/json", "access-control-allow-origin": "*" });
  res.end(JSON.stringify(body));
};
const readBody = (req) =>
  new Promise((resolve) => {
    const chunks = [];
    req.on("data", (c) => chunks.push(c));
    req.on("end", () => resolve(Buffer.concat(chunks)));
  });
const bearer = (req) => (req.headers.authorization ?? "").replace(/^Bearer\s+/i, "") || req.headers.apikey;
const userObject = () => ({ id: adminId, aud: "authenticated", role: "authenticated", email: cfg.adminEmail, app_metadata: { provider: "email" }, user_metadata: {}, created_at: new Date(0).toISOString() });
function session() {
  const now = Math.floor(Date.now() / 1000);
  const access_token = signJwt({ sub: adminId, role: "authenticated", aud: "authenticated", email: cfg.adminEmail, iat: now, exp: now + 3600, session_id: randomUUID() });
  return { access_token, token_type: "bearer", expires_in: 3600, expires_at: now + 3600, refresh_token: randomUUID(), user: userObject() };
}

// Test doubles for the shipping calculator (E2E): CEP lookup in the ViaCEP format and
// carrier quotes in the Melhor Envio format. Deterministic, so tests can assert values.
const TEST_CEPS = {
  "29055100": { cep: "29055-100", logradouro: "", bairro: "Praia do Canto", localidade: "Vitória", uf: "ES" },
  "29100010": { cep: "29100-010", logradouro: "", bairro: "Centro", localidade: "Vila Velha", uf: "ES" },
  "01001000": { cep: "01001-000", logradouro: "Praça da Sé", bairro: "Sé", localidade: "São Paulo", uf: "SP" },
};
const TEST_ME_TOKEN = "local-test";
function testCarrierQuote(body) {
  const weight = (body.products ?? []).reduce((sum, p) => sum + Number(p.weight) * Number(p.quantity), 0);
  const far = !String(body.to?.postal_code ?? "").startsWith("29");
  const pac = Math.round((18 + weight * 10 + (far ? 6 : 0)) * 100) / 100;
  return [
    { id: 1, name: "PAC", price: pac.toFixed(2), custom_price: pac.toFixed(2), delivery_time: 6, custom_delivery_time: 6, custom_delivery_range: { min: 5, max: 7 }, company: { id: 1, name: "Correios" } },
    { id: 2, name: "SEDEX", price: (pac + 14).toFixed(2), custom_price: (pac + 14).toFixed(2), custom_delivery_time: 2, custom_delivery_range: { min: 1, max: 2 }, company: { id: 1, name: "Correios" } },
    { id: 3, name: ".Package", error: "Transportadora não atende este trecho.", company: { id: 2, name: "Jadlog" } },
  ];
}

const server = http.createServer(async (req, res) => {
  const url = new URL(req.url, `http://localhost:${cfg.gatewayPort}`);
  try {
    if (req.method === "OPTIONS") {
      res.writeHead(204, { "access-control-allow-origin": "*", "access-control-allow-headers": "*", "access-control-allow-methods": "*" });
      return res.end();
    }
    // REST → PostgREST
    if (url.pathname.startsWith("/rest/v1")) {
      const headers = { ...req.headers, host: `localhost:${cfg.restPort}` };
      if (!headers.authorization && headers.apikey) headers.authorization = `Bearer ${headers.apikey}`;
      const upstream = http.request({ host: "localhost", port: cfg.restPort, method: req.method, path: url.pathname.replace(/^\/rest\/v1/, "") + url.search, headers }, (up) => {
        res.writeHead(up.statusCode ?? 502, up.headers);
        up.pipe(res);
      });
      upstream.on("error", (e) => json(res, 502, { message: e.message }));
      return req.pipe(upstream);
    }
    // Auth (email/password for the single local admin)
    if (url.pathname === "/auth/v1/token") {
      const body = JSON.parse((await readBody(req)).toString() || "{}");
      if (url.searchParams.get("grant_type") === "password") {
        if (body.email !== cfg.adminEmail || body.password !== cfg.adminPassword) return json(res, 400, { error: "invalid_grant", error_description: "Invalid login credentials", code: "invalid_credentials", msg: "Invalid login credentials" });
        return json(res, 200, session());
      }
      if (url.searchParams.get("grant_type") === "refresh_token") return json(res, 200, session());
      return json(res, 400, { error: "unsupported_grant_type" });
    }
    if (url.pathname === "/auth/v1/user") {
      const claims = verifyJwt(bearer(req));
      if (!claims?.sub) return json(res, 401, { code: 401, msg: "invalid JWT" });
      return json(res, 200, userObject());
    }
    if (url.pathname === "/auth/v1/logout") {
      res.writeHead(204);
      return res.end();
    }
    // Shipping test doubles
    const viacep = url.pathname.match(/^\/viacep\/ws\/([0-9]{8})\/json\/?$/);
    if (viacep) return json(res, 200, TEST_CEPS[viacep[1]] ?? { erro: "true" });
    if (url.pathname === "/melhor-envio/api/v2/me/shipment/calculate" && req.method === "POST") {
      if (bearer(req) !== TEST_ME_TOKEN) return json(res, 401, { message: "Unauthenticated." });
      if (!/@/.test(req.headers["user-agent"] ?? "")) return json(res, 400, { message: "User-Agent must contain a contact e-mail." });
      return json(res, 200, testCarrierQuote(JSON.parse((await readBody(req)).toString() || "{}")));
    }
    // Storage
    const pub = url.pathname.match(/^\/storage\/v1\/object\/public\/([^/]+)\/(.+)$/);
    if (pub && req.method === "GET") {
      const file = path.join(storageDir, pub[1], decodeURIComponent(pub[2]));
      if (!file.startsWith(storageDir) || !existsSync(file)) return json(res, 404, { message: "not found" });
      res.writeHead(200, { "content-type": MIME[file.split(".").pop()] ?? "application/octet-stream", "cache-control": "public, max-age=31536000" });
      return createReadStream(file).pipe(res);
    }
    const obj = url.pathname.match(/^\/storage\/v1\/object\/([^/]+)(?:\/(.+))?$/);
    if (obj) {
      const claims = verifyJwt(bearer(req));
      if (claims?.role !== "authenticated") return json(res, 403, { message: "unauthorized" });
      const bucketDir = path.join(storageDir, obj[1]);
      if ((req.method === "POST" || req.method === "PUT") && obj[2]) {
        const file = path.join(bucketDir, decodeURIComponent(obj[2]));
        if (!file.startsWith(bucketDir)) return json(res, 400, { message: "invalid path" });
        mkdirSync(path.dirname(file), { recursive: true });
        writeFileSync(file, await readBody(req));
        return json(res, 200, { Id: randomUUID(), Key: `${obj[1]}/${obj[2]}` });
      }
      if (req.method === "DELETE") {
        const { prefixes = [] } = JSON.parse((await readBody(req)).toString() || "{}");
        for (const p of prefixes) {
          const file = path.join(bucketDir, p);
          if (file.startsWith(bucketDir) && existsSync(file)) unlinkSync(file);
        }
        return json(res, 200, prefixes.map((name) => ({ name })));
      }
    }
    json(res, 404, { message: `No route for ${req.method} ${url.pathname}` });
  } catch (e) {
    json(res, 500, { message: String(e) });
  }
});
server.listen(cfg.gatewayPort, () => {
  console.log(`\n✓ Local stack ready
  Supabase URL : http://localhost:${cfg.gatewayPort}
  Anon key     : ${anonKey.slice(0, 24)}…
  Admin login  : ${cfg.adminEmail} / ${cfg.adminPassword}\n`);
});

// Always written: lets test scripts target the local stack explicitly, whatever .env.local says
writeFileSync(
  path.join(stateDir, "local.env"),
  `export NEXT_PUBLIC_SUPABASE_URL=http://localhost:${cfg.gatewayPort}\nexport NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}\nexport NEXT_PUBLIC_SITE_URL=http://localhost:3000\n` +
    // shipping calculator against the test doubles above (never the real services)
    `export CEP_API_URL=http://localhost:${cfg.gatewayPort}/viacep\nexport MELHOR_ENVIO_BASE_URL=http://localhost:${cfg.gatewayPort}/melhor-envio\nexport MELHOR_ENVIO_TOKEN=${TEST_ME_TOKEN}\nexport MELHOR_ENVIO_EMAIL=loja@example.com\n`,
);

// .env.local for the Next.js app
const envFile = path.join(root, ".env.local");
const marker = "# generated by scripts/local-stack";
if (!existsSync(envFile) || readFileSync(envFile, "utf8").startsWith(marker)) {
  writeFileSync(
    envFile,
    `${marker} — local development only\nNEXT_PUBLIC_SUPABASE_URL=http://localhost:${cfg.gatewayPort}\nNEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}\nNEXT_PUBLIC_SITE_URL=http://localhost:3000\n`,
  );
}

function shutdown() {
  shuttingDown = true;
  server.close();
  rest.kill();
  run(bin("pg_ctl"), ["-D", dataDir, "-m", "fast", "stop"], { allowFail: true });
  process.exit(0);
}
process.on("SIGINT", shutdown);
process.on("SIGTERM", shutdown);
