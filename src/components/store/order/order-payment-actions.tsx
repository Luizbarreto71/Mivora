"use client";

import { Check, Copy, CreditCard, Loader2, RefreshCw } from "lucide-react";
import { useRouter } from "next/navigation";
import { useEffect, useState, useTransition } from "react";
import { Button } from "@/components/ui/button";
import { payOrder, renewPix } from "@/lib/store/actions";

/** Opens the Mercado Pago checkout of the order (reused while valid, created again when needed). */
export function PayOrderButton({ orderId, label }: { orderId: string; label: string }) {
  const [pending, startTransition] = useTransition();
  const [error, setError] = useState<string | null>(null);
  return (
    <div className="space-y-2">
      <Button
        size="lg"
        className="w-full"
        data-mp-checkout-cta="checkout-pro"
        disabled={pending}
        onClick={() => {
          setError(null);
          startTransition(async () => {
            const result = await payOrder(orderId).catch(() => ({ ok: false as const, error: "Não foi possível abrir o pagamento agora. Tente novamente em instantes." }));
            if (result.ok) window.location.assign(result.url);
            else setError(result.error);
          });
        }}
      >
        {pending ? <Loader2 className="h-4 w-4 animate-spin" /> : <CreditCard className="h-4 w-4" strokeWidth={1.75} />}
        {pending ? "Abrindo o Mercado Pago…" : label}
      </Button>
      {error ? (
        <p className="text-sm text-danger" role="alert">
          {error}
        </p>
      ) : null}
    </div>
  );
}

/** While the payment is being confirmed (Pix, analysis), the page checks again on its own for a few minutes. */
export function PaymentAutoRefresh({ seconds = 8, maxTimes = 40 }: { seconds?: number; maxTimes?: number }) {
  const router = useRouter();
  const [count, setCount] = useState(0);
  useEffect(() => {
    if (count >= maxTimes) return;
    const timer = setTimeout(() => {
      router.refresh();
      setCount((c) => c + 1);
    }, seconds * 1000);
    return () => clearTimeout(timer);
  }, [count, maxTimes, router, seconds]);
  return null;
}

/** Pix QR code and copy-and-paste code generated by Mercado Pago for this order. */
export function PixPayment({ qrCode, qrBase64, ticketUrl, expiresAt }: { qrCode: string; qrBase64: string | null; ticketUrl: string | null; expiresAt: string | null }) {
  const [copied, setCopied] = useState(false);
  const copy = async () => {
    try {
      await navigator.clipboard.writeText(qrCode);
    } catch {
      const area = document.getElementById("pix-code") as HTMLTextAreaElement | null;
      area?.select();
      document.execCommand?.("copy");
    }
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };
  const until = expiresAt ? new Date(expiresAt).toLocaleTimeString("pt-BR", { hour: "2-digit", minute: "2-digit", timeZone: "America/Sao_Paulo" }) : null;
  return (
    <div className="mx-auto mt-8 max-w-sm text-left" aria-label="Pagamento com Pix">
      {qrBase64 ? (
        // eslint-disable-next-line @next/next/no-img-element
        <img src={`data:image/png;base64,${qrBase64}`} alt="QR Code do Pix" width={224} height={224} className="mx-auto h-56 w-56 border border-line bg-white p-2" />
      ) : null}
      <label htmlFor="pix-code" className="mt-5 block text-[0.8125rem] font-semibold">
        Pix copia e cola
      </label>
      <textarea id="pix-code" readOnly value={qrCode} rows={3} className="mt-1.5 w-full resize-none break-all rounded-[2px] border border-line bg-ivory px-3 py-2 font-mono text-xs" onFocus={(e) => e.currentTarget.select()} />
      <Button size="lg" className="mt-3 w-full" onClick={copy}>
        {copied ? <Check className="h-4 w-4" /> : <Copy className="h-4 w-4" strokeWidth={1.75} />}
        {copied ? "Código copiado" : "Copiar código Pix"}
      </Button>
      <p className="mt-3 text-xs leading-relaxed text-muted">
        Abra o app do seu banco, escolha pagar com Pix e escaneie o QR Code ou cole o código.{until ? ` O código vale até ${until}.` : ""}
      </p>
      {ticketUrl ? (
        <a href={ticketUrl} target="_blank" rel="noopener noreferrer" className="mt-2 inline-block text-xs underline underline-offset-2">
          Abrir o Pix na página do Mercado Pago
        </a>
      ) : null}
    </div>
  );
}

/** The previous Pix code expired: generates a new one for the same order. */
export function RenewPixButton({ orderId }: { orderId: string }) {
  const router = useRouter();
  const [pending, startTransition] = useTransition();
  const [error, setError] = useState<string | null>(null);
  return (
    <div className="space-y-2">
      <Button
        size="lg"
        className="w-full"
        disabled={pending}
        onClick={() => {
          setError(null);
          startTransition(async () => {
            const result = await renewPix(orderId).catch(() => ({ ok: false as const, error: "Não foi possível gerar um novo Pix agora." }));
            if (result.ok) router.refresh();
            else setError(result.error);
          });
        }}
      >
        {pending ? <Loader2 className="h-4 w-4 animate-spin" /> : <RefreshCw className="h-4 w-4" strokeWidth={1.75} />}
        {pending ? "Gerando…" : "Gerar novo código Pix"}
      </Button>
      {error ? (
        <p className="text-sm text-danger" role="alert">
          {error}
        </p>
      ) : null}
    </div>
  );
}
